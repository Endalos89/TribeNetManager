const assert=require('node:assert/strict');
const G=require('../src/isometric-core');
const S=require('../src/terrain-settings');
const U=require('../src/isometric-units');
const centre=(c,r)=>({x:1+1.5*c,y:Math.sqrt(3)/2+Math.sqrt(3)*(r+(c%2?.5:0))});
assert.equal(S.WORLD_SEED,1790425012);
assert.equal(G.WORLD_SEED,S.WORLD_SEED);
assert.equal(G.seed(S.WORLD_SEED),G.seed(String(S.WORLD_SEED)),
  'the permanent numeric world seed must not crash geometry module initialisation');
assert.equal(G.reliefSeed,S.WORLD_SEED);
assert.equal(G.coreRadius,Math.sqrt(3)/(1+Math.sqrt(3)));
assert.equal(G.subdivisions(),16);
const A={col:30,row:20},B={col:30,row:21},square=G.sharedSquare(A,B);
assert.ok(square,'adjacent hexes have one physical shared square');
assert.ok(Math.abs(Math.hypot(square.corners[0].x-square.corners[1].x,square.corners[0].y-square.corners[1].y)-G.coreRadius)<1e-9,'connector is a real square');
assert.deepEqual(square.center,{x:(centre(A.col,A.row).x+centre(B.col,B.row).x)/2,y:(centre(A.col,A.row).y+centre(B.col,B.row).y)/2});
assert.equal(G.sharedSquare(A,{col:31,row:21}),null,'non-adjacent destinations cannot fabricate a shared square');
const influence=G.regionAt(square.center.x,square.center.y);
assert.equal(influence.kind,'edge');assert.equal(influence.owners.length,2);
assert.ok(influence.owners.every(o=>o.weight>=.25-1e-9&&o.weight<=.75+1e-9));
assert.ok(Math.abs(influence.owners.reduce((sum,o)=>sum+o.weight,0)-1)<1e-9);
const triangle=G.sharedTriangle(30,20,0);
const tri=G.regionAt(triangle.center.x,triangle.center.y);
assert.equal(tri.kind,'corner');assert.equal(tri.owners.length,3);
assert.ok(tri.owners.every(o=>o.weight>=.25-1e-9&&o.weight<=.5+1e-9));
assert.ok(Math.abs(tri.owners.reduce((sum,o)=>sum+o.weight,0)-1)<1e-9);
assert.deepEqual(G.regionAt(triangle.center.x,triangle.center.y),tri);
assert.deepEqual(U.diceSlots(1),[{x:0,y:0}]);
assert.equal(U.diceSlots(6).length,6);
assert.equal(new Set(U.diceSlots(6).map(p=>p.x)).size,2);
assert.equal(new Set(U.diceSlots(6).map(p=>p.y)).size,3);
for(const n of [1,2,3,4,5,6,7,12,23])assert.equal(new Set(U.diceSlots(n).map(p=>p.x+':'+p.y)).size,n,'unit slots must not overlap');
const previous=S.get(),raw=S.exportPreset(),parsed=JSON.parse(raw);
assert.equal(parsed.worldSeed,S.WORLD_SEED);
assert.equal(parsed.format,'tribenet-terrain-preset');
S.set({hillAmplitude:.88,meshQuality:24,ruggedness:.23});
assert.equal(G.subdivisions(),24);
assert.equal(S.definitions.hillAmplitude.min,0,'hill scale can be turned off');
assert.equal(S.definitions.mountainHeight.min,0,'mountain scale can be turned off');
assert.ok(S.definitions.waterHeight.max>=.45,'water can be adjusted above the previous limit');
S.set({hillAmplitude:0,mountainHeight:0,waterHeight:.45,foothillFlatness:.30});
const c=centre(30,20),palette=()=> '#83b653';
const ocean=G.surface(c.x,c.y,()=>({terrain:'O'}),palette);
const flat=G.surface(c.x,c.y,()=>({terrain:'PR'}),palette);
const mountain=G.surface(c.x,c.y,()=>({terrain:'HSM'}),palette);
assert.equal(ocean.z,.45,'water level may be increased to 0.45');
assert.ok(flat.z>ocean.z,'land stays just above the raised water plane');
assert.ok(mountain.z<flat.z+.12,'setting mountain height to zero removes its baseline peak');
S.set({hillAmplitude:.88,mountainHeight:.83,waterHeight:.10,foothillFlatness:.20});
S.set({waterHeight:.125,plainsRelief:.08,plainsTexture:.3,waveStrength:.75});
const oceanCenter=centre(30,20),sea=G.surface(oceanCenter.x,oceanCenter.y,()=>({terrain:'O'}),()=> '#337f98');
assert.equal(sea.z,.125,'water level adjusts the physical ocean plane');
const plains=G.surface(oceanCenter.x,oceanCenter.y,()=>({terrain:'PR'}),()=> '#83b653');
assert.ok(plains.z>sea.z&&plains.z-sea.z<.08,'plains remain close above sea level');
assert.notEqual(sea.color,'#337f98','water colour has deterministic subtle variation');
assert.equal(JSON.parse(S.exportPreset()).settings.waterHeight,.125,'numeric tuning is exported');
assert.equal(S.value('hillAmplitude'),.88);
assert.equal(S.value('ruggedness'),.23);
assert.throws(()=>S.importPreset(JSON.stringify({...parsed,worldSeed:12})),/seed/);
S.importPreset(raw);
assert.deepEqual(S.get(),previous);
assert.equal(G.subdivisions(),16);
console.log('Fixed world seed, rhombitrihexagon connectors, seeded weights, die layouts and developer preset tests passed.');
